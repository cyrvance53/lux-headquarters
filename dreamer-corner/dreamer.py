#!/usr/bin/env python3
"""The Dream Maker — staging job mechanism (Lux Playground corner).

House pipeline, as actually practised by the daily dream drip
(see ~/workspace/goals/facebook-group-launch-ai-art-wild-videos/hidden_files/dream-drip-log.md):

  CODE steps (this file):
    1. Take a scene description -> create a job folder + house prompt.
    2. Finish a generated master: strip generator audio, lay a Haven song
       excerpt under it, loudnorm to -14 LUFS (house target), gentle fades,
       embed a fingerprint in metadata, normalise to 720x1280.
    3. QA the finished scene with ffprobe + volumedetect and record it.

  AGENT step (NOT code, and not faked here):
    The master itself is generated by Muse's own media pipeline
    (media.generate_video) at runtime, by an agent, from the job's
    prompt.txt. A job sits at status "awaiting_generation" until an agent
    generates jobs/<id>/master.mp4. There is no vendor video API and no
    local GPU model in this step — that is the honest seam.

Usage:
  python3 dreamer.py new "a scene description"
  python3 dreamer.py finish <job-id>
  python3 dreamer.py status <job-id>
"""
import json, re, subprocess, sys, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent
JOBS = ROOT / "jobs"
SONG = Path.home() / "workspace/goals/fiverr-ai-services-shop/files/music/million-times-better-supersong-take2.mp3"
SONG_OFFSET = "45"  # house pattern: excerpt starts at 0:45
SONG_NAME = "A Million Times Better — Take 2 (Haven)"
PROMPT_TEMPLATE = ("A short dreamlike cinematic vertical video, photoreal and warm: "
                   "{desc}. No people, no text, no dialogue.")


def slugify(text):
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s[:40] or "scene"


def new_job(description):
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    jid = f"{stamp}-{slugify(description)}"
    jdir = JOBS / jid
    jdir.mkdir(parents=True, exist_ok=False)
    desc = description.strip().rstrip(".")
    (jdir / "prompt.txt").write_text(PROMPT_TEMPLATE.format(desc=desc) + "\n")
    job = {"id": jid, "service": "The Dream Maker", "status": "awaiting_generation",
           "description": description, "created": datetime.datetime.now().isoformat(timespec="seconds"),
           "note": "Next step is the agent seam: Muse's media pipeline generates master.mp4 from prompt.txt, then `dreamer.py finish` completes the job in code."}
    (jdir / "job.json").write_text(json.dumps(job, indent=2) + "\n")
    return job


def _run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"command failed: {' '.join(map(str, cmd))}\n{r.stderr[-2000:]}")
    return r.stdout


def probe(path):
    out = _run(["ffprobe", "-v", "error", "-show_streams", "-show_format", "-of", "json", str(path)])
    return json.loads(out)


def finish(jid):
    jdir = JOBS / jid
    master = jdir / "master.mp4"
    if not master.exists():
        raise SystemExit(f"SEAM: {master} does not exist yet — the scene must be generated by an agent "
                         f"via Muse's media pipeline from prompt.txt before code can finish it.")
    job = json.loads((jdir / "job.json").read_text())
    dur = float(probe(master)["format"]["duration"])
    dur = min(dur, 10.0)
    scene = jdir / "scene.mp4"
    fade_out_start = max(dur - 1.0, 0)
    _run(["ffmpeg", "-y", "-v", "error",
          "-i", str(master), "-ss", SONG_OFFSET, "-i", str(SONG),
          "-filter_complex",
          ("[0:v]scale=720:1280:force_original_aspect_ratio=increase,crop=720:1280,setsar=1[v];"
           f"[1:a]loudnorm=I=-14:TP=-1:LRA=11,afade=t=in:st=0:d=0.5,"
           f"afade=t=out:st={fade_out_start:.2f}:d=1.0[a]"),
          "-map", "[v]", "-map", "[a]", "-t", f"{dur:.3f}",
          "-c:v", "libx264", "-pix_fmt", "yuv420p", "-r", "24",
          "-c:a", "aac", "-b:a", "160k",
          "-metadata", f"title=The Dream Maker — {job['description'][:60]}",
          "-metadata", f"comment=LUX-DREAM-MAKER-STAGING-{jid}",
          str(scene)])
    # QA, house style: ffprobe + volume check
    info = probe(scene)
    vol = subprocess.run(["ffmpeg", "-i", str(scene), "-af", "volumedetect", "-f", "null", "-"],
                         capture_output=True, text=True).stderr
    mean = re.search(r"mean_volume:\s*([-\d.]+) dB", vol)
    job.update({"status": "done", "scene": "scene.mp4", "song": SONG_NAME,
                "finished": datetime.datetime.now().isoformat(timespec="seconds"),
                "qa": {"duration_s": round(float(info["format"]["duration"]), 2),
                       "streams": [{"type": s["codec_type"], "codec": s["codec_name"],
                                    "width": s.get("width"), "height": s.get("height")} for s in info["streams"]],
                       "mean_volume_db": float(mean.group(1)) if mean else None}})
    (jdir / "job.json").write_text(json.dumps(job, indent=2) + "\n")
    (JOBS / "latest.json").write_text(json.dumps(
        {"id": jid, "scene": f"jobs/{jid}/scene.mp4", "description": job["description"]}, indent=2) + "\n")
    return job


if __name__ == "__main__":
    if len(sys.argv) >= 3 and sys.argv[1] == "new":
        print(json.dumps(new_job(" ".join(sys.argv[2:])), indent=2))
    elif len(sys.argv) == 3 and sys.argv[1] == "finish":
        print(json.dumps(finish(sys.argv[2]), indent=2))
    elif len(sys.argv) == 3 and sys.argv[1] == "status":
        print((JOBS / sys.argv[2] / "job.json").read_text())
    else:
        raise SystemExit(__doc__)
